#!/usr/bin/env python3
"""Generate `src/schemas/generated.ts` from the upstream Python MCP server.

The tool catalogue (names, descriptions, input schemas and output schemas) is
derived by pydantic from the Python function signatures and the OpenAPI-generated
models. Rather than transcribing ~50 KB of JSON Schema by hand, this script asks
the upstream FastMCP server for its catalogue and emits it as a TypeScript
module, so the ported server advertises byte-identical schemas.

Usage:
    PYTHONPATH=<upstream>/src python3 tools/gen_schemas.py <out.ts>
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path

# The upstream app builds its client list from config at lifespan start, not at
# import time, so a config file is not required to enumerate the catalogue.
os.environ.setdefault("SHS_MCP_CONFIG", str(Path(__file__).parent / "_gen_config.yaml"))

GEN_CONFIG = Path(__file__).parent / "_gen_config.yaml"
if not GEN_CONFIG.exists():
    GEN_CONFIG.write_text(
        "servers:\n  local:\n    default: true\n    url: \"http://localhost:18080\"\n"
        "mcp:\n  transport: stdio\n"
    )

from spark_history_mcp.core.app import mcp  # noqa: E402


async def main() -> None:
    out_path = Path(sys.argv[1])

    tools = await mcp.list_tools()
    prompts = await mcp.list_prompts()

    tool_entries = []
    for tool in sorted(tools, key=lambda t: t.name):
        tool_entries.append(
            {
                "name": tool.name,
                "description": tool.description,
                "inputSchema": tool.inputSchema,
                "outputSchema": tool.outputSchema,
            }
        )

    prompt_entries = []
    for prompt in sorted(prompts, key=lambda p: p.name):
        prompt_entries.append(
            {
                "name": prompt.name,
                "title": prompt.title,
                "description": prompt.description,
                "arguments": [
                    {
                        "name": arg.name,
                        "description": arg.description,
                        "required": bool(arg.required),
                    }
                    for arg in (prompt.arguments or [])
                ],
            }
        )

    header = """/**
 * Tool and prompt catalogue metadata.
 *
 * GENERATED by tools/gen_schemas.py from the upstream Python server's FastMCP
 * catalogue (which pydantic derives from the tool signatures and the
 * OpenAPI-generated models). Do not edit by hand.
 */

export interface ToolCatalogEntry {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
  outputSchema: Record<string, unknown> | null;
}

export interface PromptArgumentEntry {
  name: string;
  description: string | null;
  required: boolean;
}

export interface PromptCatalogEntry {
  name: string;
  title: string | null;
  description: string;
  arguments: PromptArgumentEntry[];
}

export const TOOL_CATALOG: ToolCatalogEntry[] = """

    # Key order is preserved: pydantic emits schema properties in the Python
    # function's signature order, and the validator reports errors in that order.
    body = json.dumps(tool_entries, indent=2)
    prompt_body = json.dumps(prompt_entries, indent=2)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        header
        + body
        + ";\n\nexport const PROMPT_CATALOG: PromptCatalogEntry[] = "
        + prompt_body
        + ";\n"
    )
    print(f"wrote {out_path}: {len(tool_entries)} tools, {len(prompt_entries)} prompts")


if __name__ == "__main__":
    asyncio.run(main())
