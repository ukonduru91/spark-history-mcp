#!/usr/bin/env python3
"""Generate `src/models/generated.ts` from the Python OpenAPI-generated models.

The Python MCP returns the generated pydantic models straight to FastMCP, which
serializes them with ``model_dump(mode="json", by_alias=True)``. That means the
wire format is:

* keys = the pydantic **aliases** (camelCase, i.e. the Spark REST JSON names),
* in **field definition order**,
* every field present, ``null`` when absent,
* plus a trailing ``additional_properties`` object holding any keys the schema
  does not know about.

This script reads the generated Python models and emits TypeScript interfaces
plus a runtime schema table so the TypeScript port can reproduce that byte for
byte.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MODELS_DIR = Path(sys.argv[1])
OUT_FILE = Path(sys.argv[2])

CLASS_RE = re.compile(r"^class (\w+)\(BaseModel\):")
FIELD_RE = re.compile(
    r"^    (?P<name>[a-z_][a-z0-9_]*): (?P<type>.+?)"
    r"(?: = (?P<default>.+))?$"
)
ALIAS_RE = re.compile(r'alias="(?P<alias>[^"]+)"')

SCALARS = {
    "StrictStr": "string",
    "StrictInt": "number",
    "StrictFloat": "number",
    "StrictBool": "boolean",
    "str": "string",
    "int": "number",
    "float": "number",
    "bool": "boolean",
    "Any": "any",
    "object": "any",
}


def strip_optional(type_str: str) -> str:
    type_str = type_str.strip()
    if type_str.startswith("Optional[") and type_str.endswith("]"):
        return type_str[len("Optional[") : -1].strip()
    return type_str


def split_top_level(inner: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for ch in inner:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def parse_type(type_str: str, known: set[str]):
    """Return (ts_type, runtime_descriptor)."""
    t = strip_optional(type_str)

    if t.startswith("Union[") and t.endswith("]"):
        options = split_top_level(t[len("Union[") : -1])
        ts_parts, descs = [], []
        for option in options:
            ts, desc = parse_type(option, known)
            ts_parts.append(ts)
            descs.append(desc)
        # Spark's numeric unions (float|int) collapse to `number`.
        unique = sorted(set(ts_parts))
        if unique == ["number"]:
            return "number", {"k": "s"}
        return " | ".join(dict.fromkeys(ts_parts)), descs[0]

    if t.startswith("List[") and t.endswith("]"):
        item_ts, item_desc = parse_type(t[len("List[") : -1], known)
        return f"Array<{item_ts}>", {"k": "l", "i": item_desc}

    if t.startswith("Dict[") and t.endswith("]"):
        parts = split_top_level(t[len("Dict[") : -1])
        value_ts, value_desc = parse_type(parts[-1], known)
        return f"Record<string, {value_ts}>", {"k": "d", "i": value_desc}

    if t in SCALARS:
        return SCALARS[t], {"k": "s"}

    if t in known:
        return t, {"k": "m", "m": t}

    return "any", {"k": "s"}


def parse_model_file(path: Path):
    class_name = None
    fields = []
    for raw_line in path.read_text().splitlines():
        match = CLASS_RE.match(raw_line)
        if match:
            class_name = match.group(1)
            continue
        if class_name is None:
            continue
        if raw_line.startswith("    __properties") or raw_line.startswith(
            "    model_config"
        ):
            break
        field = FIELD_RE.match(raw_line)
        if not field:
            continue
        name = field.group("name")
        if name == "additional_properties":
            continue
        default = field.group("default") or ""
        alias_match = ALIAS_RE.search(default)
        alias = alias_match.group("alias") if alias_match else name
        fields.append((name, alias, field.group("type")))
    return class_name, fields


def main() -> None:
    parsed = {}
    for path in sorted(MODELS_DIR.glob("*.py")):
        if path.name == "__init__.py":
            continue
        class_name, fields = parse_model_file(path)
        if class_name:
            parsed[class_name] = fields

    known = set(parsed)

    lines = [
        "/**",
        " * Spark History Server REST models.",
        " *",
        " * GENERATED by tools/gen_models.py from the upstream Python project's",
        " * OpenAPI-generated pydantic models. Do not edit by hand.",
        " *",
        " * Property names are the pydantic aliases (== the Spark REST JSON names),",
        " * declared in field-definition order so a JSON dump matches the Python",
        " * server's `model_dump(by_alias=True)` output exactly.",
        " */",
        "",
        "/* eslint-disable @typescript-eslint/no-explicit-any */",
        "",
    ]

    for class_name in sorted(parsed):
        fields = parsed[class_name]
        lines.append(f"export interface {class_name} {{")
        for _name, alias, type_str in fields:
            ts_type, _desc = parse_type(type_str, known)
            key = alias if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", alias) else f'"{alias}"'
            lines.append(f"  {key}?: {ts_type} | null;")
        lines.append("  additional_properties?: Record<string, any>;")
        lines.append("}")
        lines.append("")

    lines.append("export type FieldKind = \"s\" | \"m\" | \"l\" | \"d\";")
    lines.append("")
    lines.append("export interface FieldDescriptor {")
    lines.append("  k: FieldKind;")
    lines.append("  m?: string;")
    lines.append("  i?: FieldDescriptor;")
    lines.append("}")
    lines.append("")
    lines.append("export interface ModelField {")
    lines.append("  alias: string;")
    lines.append("  desc: FieldDescriptor;")
    lines.append("}")
    lines.append("")
    lines.append("export const MODEL_SCHEMAS: Record<string, ModelField[]> = {")
    for class_name in sorted(parsed):
        lines.append(f"  {class_name}: [")
        for _name, alias, type_str in parsed[class_name]:
            _ts, desc = parse_type(type_str, known)
            lines.append(
                f'    {{ alias: "{alias}", desc: {render_desc(desc)} }},'
            )
        lines.append("  ],")
    lines.append("};")
    lines.append("")

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(lines))
    print(f"wrote {OUT_FILE} ({len(parsed)} models)")


def render_desc(desc) -> str:
    if desc["k"] == "s":
        return '{ k: "s" }'
    if desc["k"] == "m":
        return f'{{ k: "m", m: "{desc["m"]}" }}'
    return f'{{ k: "{desc["k"]}", i: {render_desc(desc["i"])} }}'


if __name__ == "__main__":
    main()
